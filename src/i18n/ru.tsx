/** Russian plural helper: ruPlural(3, ['стартап', 'стартапа', 'стартапов']). */
function ruPlural(n: number, [one, few, many]: [string, string, string]): string {
  const abs = Math.abs(n) % 100
  const d = abs % 10
  if (abs > 10 && abs < 20) return many
  if (d === 1) return one
  if (d >= 2 && d <= 4) return few
  return many
}

